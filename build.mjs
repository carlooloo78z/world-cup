// Dependency-free bundle for opening index.html directly from File Explorer.
// Sources remain ES modules for development and Node regression tests.
import {readFile,writeFile} from 'node:fs/promises';
import {resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=dirname(fileURLToPath(import.meta.url));
const files=['assets/three.module.js','src/data.js','src/third-allocations.js','src/tournament.js','src/simulation.js','src/athlete.js','src/players.js','src/presentation.js','src/world.js','src/audio.js','src/app.js'];
const ids=new Map(files.map((name,i)=>[resolve(root,name),'m'+i]));
const sections=[];
for(const [i,name] of files.entries()){
 let code=await readFile(resolve(root,name),'utf8');
 const exports=[];
 code=code.replace(/^import\s+(.+?)\s+from\s+['"](.+?)['"];\s*$/gm,(_,bindings,specifier)=>{
  const id=ids.get(resolve(root,dirname(name),specifier));
  if(!id)throw Error('Unbundled dependency: '+specifier);
  if(bindings.startsWith('* as '))return 'const '+bindings.slice(5)+'=modules.'+id+';';
  if(bindings.startsWith('{'))return 'const '+bindings.replace(/\bas\b/g,':')+'=modules.'+id+';';
  throw Error('Unsupported import: '+bindings);
 });
 code=code.replace(/\bexport\s+(const|let|var|function|class)\s+([A-Za-z_$][\w$]*)/g,(_,kind,key)=>{exports.push([key,key]);return kind+' '+key;});
 code=code.replace(/\bexport\s*\{([^}]+)\}\s*;?/g,(_,list)=>{for(const part of list.split(',')){const [local,alias]=part.trim().split(/\s+as\s+/);exports.push([alias||local,local]);}return '';});
 sections.push(`// ${name}\nmodules.m${i}=(()=>{\n${code}\nreturn {${exports.map(([key,value])=>JSON.stringify(key)+':'+value).join(',')}};\n})();`);
}
const bundle='/* WORLD 26: generated by node build.mjs. Third-party licenses are in assets/. */\n(()=>{\n"use strict";\nconst modules={};\n'+sections.join('\n')+'\n})();\n';
const target=resolve(root,'game.bundle.js');
if(process.argv.includes('--check')){
 if(await readFile(target,'utf8')!==bundle)throw Error('game.bundle.js is stale. Run node build.mjs.');
 console.log('Browser bundle matches all source modules.');
}else{await writeFile(target,bundle);console.log('Built game.bundle.js — '+Buffer.byteLength(bundle).toLocaleString()+' bytes.');}
